"""Validate backend capability records and emit the capability report.

A backend is GO only when every gate is closed, every pad flag is true and
every pad timing number is present. The script refuses to let a backend
declare status=supported while any of those is false: that is the whole
point of a capability report (checklist section 8).
"""
import glob
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
BACKENDS = ROOT / "backends"
REPORTS = ROOT / "reports"

GATES = {
    "G1": "3.3 V bidirectional LVTTL pad with ESD, level shifter and power-up Hi-Z",
    "G2": "no backend may fall back to a core standard cell to drive external DQ",
    "G3": "a backend without a qualified IO macro is marked unsupported, not downgraded",
    "G4": "no characterized delay/phase cell -> fixed-phase only (here: none)",
    "G5": "pad timing (tOE_on/off, slew, input threshold) characterized",
    "G6": "clock forwarding path and read capture phase from characterized delay/PLL",
}

PAD_FLAGS = [
    "schematic_drawn", "netlist_characterized", "spice_verified",
    "drive_strength_selected", "esd_verified", "level_shifter_verified",
    "powerup_hiz_verified",
]
PAD_NUMBERS = ["toe_on_ps", "toe_off_ps"]

FORBIDDEN_CLAIMS = ("tapeout", "signoff", "silicon", "ready for production")


def validate(d, path, errors):
    for key in ("name", "pdk", "scl", "status", "capability_level",
                "core_voltage_v", "vddio_v", "io_standard", "pad",
                "phase_control", "open_gates", "allowed_claims",
                "disallowed_claims"):
        if key not in d:
            errors.append(f"{path}: missing key '{key}'")
    if "pad" in d:
        for key in PAD_FLAGS + PAD_NUMBERS:
            if key not in d["pad"]:
                errors.append(f"{path}: pad.{key} missing")
    for g in d.get("open_gates", []) or []:
        if g not in GATES:
            errors.append(f"{path}: unknown gate '{g}'")
    for c in d.get("allowed_claims", []) or []:
        if any(w in c.lower() for w in FORBIDDEN_CLAIMS):
            errors.append(f"{path}: allowed_claims contains a tapeout claim: {c!r}")


def evaluate(d):
    reasons = []
    for g in d.get("open_gates", []) or []:
        reasons.append(f"open gate {g}: {GATES[g]}")
    for k in PAD_FLAGS:
        if d["pad"].get(k) is not True:
            reasons.append(f"pad.{k} is not true")
    for k in PAD_NUMBERS:
        if d["pad"].get(k) is None:
            reasons.append(f"pad.{k} is null (uncharacterized)")
    if not d["phase_control"].get("capture_modes"):
        reasons.append("phase_control.capture_modes is empty")

    if d.get("is_behavioral"):
        return "SIM_ONLY", ["behavioral backend: simulation only, never tapeout"]
    if d["status"] == "supported" and not reasons:
        return "GO", []
    if d["status"] == "supported" and reasons:
        return "INVALID", ["status=supported but capability evidence is incomplete"] + reasons
    return "NO_GO", reasons or ["status is not 'supported'"]


def main():
    errors = []
    rows = []
    paths = sorted(glob.glob(str(BACKENDS / "*.yaml")))
    if not paths:
        print("no backend capability files found", file=sys.stderr)
        return 2
    for p in paths:
        with open(p) as fh:
            d = yaml.safe_load(fh)
        validate(d, Path(p).name, errors)
        decision, reasons = evaluate(d)
        if decision == "INVALID":
            errors.append(f"{Path(p).name}: {reasons[0]}")
        rows.append((d, decision, reasons))

    if errors:
        for e in errors:
            print("ERROR " + e, file=sys.stderr)
        return 1

    REPORTS.mkdir(exist_ok=True)
    md = [
        "# SDRAM PHY backend capability report",
        "",
        "Generated by generator/check_capabilities.py. Do not edit by hand.",
        "",
        "**Overall: NO_GO for external SDRAM tapeout on every silicon backend.**",
        "The only usable backend today is generic_sim, which is verification-only.",
        "",
        "| Backend | PDK | status | level | open gates | decision |",
        "|---|---|---|---|---|---|",
    ]
    for d, decision, _ in rows:
        gates = ", ".join(d.get("open_gates", []) or []) or "none"
        md.append(f"| {d['name']} | {d['pdk']} | {d['status']} | "
                  f"{d['capability_level']} | {gates} | **{decision}** |")
    md += ["", "## Gate definitions", ""]
    for k, v in GATES.items():
        md.append(f"- **{k}**: {v}")
    md += ["", "## Per-backend blockers", ""]
    for d, decision, reasons in rows:
        md.append(f"### {d['name']} — {decision}")
        md.append("")
        for r in reasons:
            md.append(f"- {r}")
        if d.get("notes"):
            md.append(f"- Note: {d['notes']}")
        md += [f"- Existing IO library: {d['existing_io_library']['name']} "
               f"({d['existing_io_library']['role']})",
               f"- Core {d['core_voltage_v']} V / VDDIO {d['vddio_v']} V, "
               f"level shifter required: {d['level_shifter_required']}",
               f"- Disallowed claims: {', '.join(d['disallowed_claims'])}",
               ""]
    md += [
        "## What this report does not claim",
        "",
        "- No backend has TLP/HBM ESD qualification. The gf180 pad has BSIM",
        "  pulse stress and GF180 DRC ESD/LU rule checks only; `esd_verified`",
        "  therefore stays false and the formal decision stays NO_GO.",
        "- The gf180 pad schematic is generated and LVS-extracted; its tOE_on/off",
        "  and delay numbers are SPICE design assumptions, not silicon measurements.",
        "- Existing GPIO libraries are structural references only; per",
        "  docs/ARCHITECTURE.md they are not this design's pads.",
        "- No phase-control resource (PLL/DLL/characterized delay cell) is available,",
        "  so even a fixed-phase claim is withheld (gate G4).",
        "- No IBIS, package/PCB SI/PI or full PVT signoff has been run.",
        "",
    ]
    (REPORTS / "capability_report.md").write_text("\n".join(md) + "\n")

    payload = {
        "overall_decision": "NO_GO",
        "generated_by": "generator/check_capabilities.py",
        "gates": GATES,
        "backends": [
            {
                "name": d["name"], "pdk": d["pdk"], "scl": d["scl"],
                "status": d["status"], "capability_level": d["capability_level"],
                "decision": decision, "open_gates": d.get("open_gates", []),
                "blockers": reasons,
                "pad": d["pad"], "phase_control": d["phase_control"],
                "allowed_claims": d["allowed_claims"],
            }
            for d, decision, reasons in rows
        ],
    }
    (REPORTS / "capability_report.json").write_text(json.dumps(payload, indent=2) + "\n")

    for d, decision, _ in rows:
        print(f"{d['name']:12s} {decision}")
    print(f"\ncapability report: {REPORTS / 'capability_report.md'}")
    print("overall: NO_GO")
    return 0


if __name__ == "__main__":
    sys.exit(main())
