"""Emit the ics55 3.3 V ESD clamp prototype (STUDY_ONLY).

This is deliberately NOT part of the ics55 SDR pad map and NOT simulatable:
all sizes/gate resistors are null. The output is a topology prototype for
layout/TLP review, not an ESD-qualified cell.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPECS = ROOT / "specs" / "pads"
OUT = ROOT / "sch" / "pads" / "ics55"
REPORTS = ROOT / "reports"


def main():
    spec = yaml.safe_load(open(SPECS / "ics55_esd_3v3.yaml"))
    maps = {d["backend"]: d for d in
            (yaml.safe_load(open(p)) for p in (SPECS / "devices").glob("*.yaml"))}
    dev = maps["ics55"]

    if spec["meta"]["status"] != "STUDY_ONLY":
        print("ERROR: status must be STUDY_ONLY", file=sys.stderr)
        return 1
    for p in spec["params"]:
        if p["value"] is not None or p["status"] != "TBD":
            print("ERROR: %s must stay null/TBD" % p["id"], file=sys.stderr)
            return 1
    for key in ("nmos", "pmos"):
        if spec["devices"][key] != dev["slots"]["NMOS_IO" if key == "nmos"
                                                else "PMOS_IO"]["device"]:
            print("ERROR: %s device does not match the ics55 map" % key, file=sys.stderr)
            return 1

    tokens = {
        "DEV_NMOS": spec["devices"]["nmos"],
        "DEV_PMOS": spec["devices"]["pmos"],
        "TOPOLOGY": spec["meta"]["topology"],
        "LICENSE": spec["meta"]["license"],
        "SOURCE": spec["meta"]["source"],
    }
    for p in spec["params"]:
        tokens["P_" + p["id"]] = p["id"]

    body = (SPECS / "templates" / "ics55_esd_3v3.spice.tpl").read_text()
    for k, v in tokens.items():
        body = body.replace("@@" + k + "@@", str(v))
    if "@@" in body:
        print("ERROR: unresolved template token", file=sys.stderr)
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "esd_ggnmos_3v3.spice").write_text(body)
    manifest = {
        "generated_by": "generator/emit_ics55_esd.py",
        "backend": "ics55",
        "status": "STUDY_ONLY",
        "signoff": False,
        "simulatable": False,
        "topology": spec["meta"]["topology"],
        "devices": spec["devices"],
        "unresolved_params": [p["id"] for p in spec["params"]],
        "source": spec["meta"]["source"],
        "license": spec["meta"]["license"],
        "measurements": spec["measurements"],
    }
    (OUT / "esd_ggnmos_3v3_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    readme = """# ics55 3.3 V ESD clamp prototype (GENERATED)

**STUDY_ONLY. NOT SIMULATABLE. NOT A QUALIFIED ESD CELL.**

Generated by `generator/emit_ics55_esd.py` from
`specs/pads/ics55_esd_3v3.yaml` and `specs/pads/templates/ics55_esd_3v3.spice.tpl`.

- PAD -> VSSIO: GGNMOS, gate resistor to VSSIO
- PAD -> VDDIO: GGPMOS, gate resistor to VDDIO
- VDDIO -> VSSIO: GGNMOS power clamp
- All W/L/NF/R are null (see `esd_ggnmos_3v3_manifest.json`).
- BSIM4 does not model snapback; TLP/HBM/latch-up evidence is required.
- Do NOT bind this into the ics55 SDR pad; `specs/pads/devices/ics55.yaml`
  keeps `custom_esd.status: STUDY_ONLY`.

See `docs/ICS55_ESD_3V3.md`.
"""
    (OUT / "esd_ggnmos_3v3_README.md").write_text(readme)
    report = ["# ics55 3.3 V ESD prototype", "",
              "**STUDY_ONLY. NOT A QUALIFIED ESD CELL.**", "",
              "- topology: " + spec["meta"]["topology"],
              "- devices: " + ", ".join(spec["devices"].values()),
              "- unresolved params: %d (all null)" % len(spec["params"]),
              "- source: " + spec["meta"]["source"], "",
              "Not performed: SPICE sizing, TLP, HBM/CDM, latch-up, HTOL, DRC.", ""]
    (REPORTS / "ics55_esd_3v3.md").write_text("\n".join(report) + "\n")
    print("ics55 esd prototype: STUDY_ONLY, %d unresolved params" % len(spec["params"]))
    print("report: reports/ics55_esd_3v3.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
