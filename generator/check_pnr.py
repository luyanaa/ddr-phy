"""Summarize the constrained LibreLane run into reports/pnr_gf180.md-style JSON.

Reads flow/runs/<spec>/final/metrics.json and the post-PnR STA reports.
Exit status is 0 only when every setup/hold corner is non-negative and the
DRC/LVS checks passed.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUN = ROOT / "flow" / "runs" / "sky130"
OUT = ROOT / "reports" / "pnr_sky130.json"


def main():
    spec = "sky130"
    if "--spec" in sys.argv:
        spec = sys.argv[sys.argv.index("--spec") + 1]
    run = ROOT / "flow" / "runs" / spec
    if "--top" in sys.argv:
        run = ROOT / "flow" / "runs" / ("%s-%s" % (spec, sys.argv[sys.argv.index("--top") + 1]))
    m = json.loads((run / "final" / "metrics.json").read_text())
    corners = {}
    for k, v in m.items():
        if k.startswith("timing__setup__ws__corner:"):
            c = k.split(":", 1)[1]
            corners.setdefault(c, {})["setup_ws"] = v
        elif k.startswith("timing__hold__ws__corner:"):
            c = k.split(":", 1)[1]
            corners.setdefault(c, {})["hold_ws"] = v
    setup_min = min(v.get("setup_ws", 1e9) for v in corners.values())
    hold_min = min(v.get("hold_ws", 1e9) for v in corners.values())

    def rpt_count(step, pat="violation"):
        p = run / step / "reports"
        if not p.exists():
            return None
        n = 0
        for f in p.glob("*.rpt"):
            try:
                n += f.read_text().lower().count(pat)
            except OSError:
                pass
        return n

    rep = {
        "generated_by": "generator/check_pnr.py",
        "flow": "LibreLane, spec=%s, constrained (PNR_SDC_FILE)" % spec,
        "constraints": "flow/sdr_phy.sdc, generated by generator/emit_sdc.py, 0 TBD",
        "corners": corners,
        "worst_setup_ws_ns": setup_min,
        "worst_hold_ws_ns": hold_min,
        "metrics": {k: m[k] for k in (
            "design__instance__count", "design__die__area") if k in m},
        "final_artifacts": {
            "gds": "flow/runs/%s/final/gds/" % spec,
            "sdf": "flow/runs/%s/final/sdf/" % spec,
            "spef": "flow/runs/%s/final/spef/" % spec,
        },
        "status": "GO" if setup_min >= 0 and hold_min >= 0 else "NO_GO",
        "not_covered": [
            "the harden is sdr_phy (the digital core), not sdram_phy_top with "
            "the real pad macro",
            "sky130 standard cells, not GF180",
            "SDF back-annotated gate-level simulation not run",
            "t_uncertainty is a conservative bound, not a measurement",
        ],
    }
    rep["spec"] = spec
    top_name = None
    if "--top" in sys.argv:
        top_name = sys.argv[sys.argv.index("--top") + 1]
        rep["top"] = top_name
    suffix = spec.replace("-", "_") + ("_" + top_name if top_name else "")
    out = ROOT / "reports" / ("pnr_%s.json" % suffix)
    out.write_text(json.dumps(rep, indent=2) + "\n")
    print("wrote %s" % out)
    print("  worst setup %.3f ns, worst hold %.3f ns -> %s"
          % (setup_min, hold_min, rep["status"]))
    for c, v in sorted(corners.items()):
        print("  %-22s setup %+.3f  hold %+.3f"
              % (c, v.get("setup_ws", 0), v.get("hold_ws", 0)))
    return 0 if rep["status"] == "GO" else 1


if __name__ == "__main__":
    sys.exit(main())
