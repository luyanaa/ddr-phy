"""Apply foundry/DRM evidence to the 8 deferred pdk_rules.

Companion to extract_pdk_rules.py (which reads LOCAL PDK rule files). This
one reads specs/pads/foundry_data.yaml: values transcribed from the public
GF180MCU Design Rule Manual on 2026-11-16, each with URL, section, verbatim
snippet, caveats and a semantic_match verdict.

Only entries with decision=fill AND semantic_match=exact are written into
pdk_rules, with status foundry_doc (weaker than verified: a web source
cannot be re-opened offline, and the docs are an Experimental Preview).
Everything else stays TBD with an explicit blocked_by reason.

Usage: python3 generator/extract_foundry_data.py [--check]
"""
import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "specs" / "pads" / "foundry_data.yaml"
CONSTRAINTS = ROOT / "specs" / "pads" / "constraints.yaml"
REPORTS = ROOT / "reports"
MARK_BEGIN = "# === BEGIN GENERATED foundry_data ==="
MARK_END = "# === END GENERATED foundry_data ==="


def validate(d, errors):
    if d["meta"].get("evidence_class") != "foundry_doc":
        errors.append("meta.evidence_class must be foundry_doc")
    ids = set()
    for x in d["data"]:
        rid = x["id"]
        if rid in ids:
            errors.append("duplicate entry " + rid)
        ids.add(rid)
        for k in ("applies_to", "decision", "semantic_match", "source_url",
                  "drm_section", "verbatim"):
            if not x.get(k) and x["decision"] != "defer":
                errors.append("%s: missing %s" % (rid, k))
        if x["decision"] == "fill":
            if x["semantic_match"] != "exact":
                errors.append("%s: fill requires semantic_match=exact" % rid)
            if not isinstance(x.get("value"), (int, float)):
                errors.append("%s: fill requires numeric value" % rid)
            if not x.get("caveats"):
                errors.append("%s: fill requires caveats" % rid)
            if not str(x.get("source_url", "")).startswith("https://"):
                errors.append("%s: fill requires https source_url" % rid)
        else:
            if not x.get("blocked_by") and not x.get("note"):
                errors.append("%s: defer requires blocked_by or note" % rid)


def apply_to_constraints(fill_map, d, errors):
    text = CONSTRAINTS.read_text()
    lines = []
    filled = set()
    for line in text.splitlines():
        m = re.match(r"^(\s*-\s*\{id:\s*)([A-Z_]+)(,.*)$", line)
        if m and m.group(2) in fill_map:
            rid, rest = m.group(2), m.group(3)
            url = fill_map[rid]["url"]
            rest = re.sub(r"value:\s*(null|[\d.eE+-]+)", "value: %s" % fill_map[rid]["value"], rest)
            rest = re.sub(r"status:\s*\w+", "status: foundry_doc", rest)
            rest = re.sub(r",\s*foundry_from:\s*\"[^\"]*\"", "", rest)
            rest = re.sub(r",\s*verified_from:\s*\"[^\"]*\"", "", rest)
            rest = rest.rstrip()
            if rest.endswith("}"):
                rest = rest[:-1].rstrip() + ', foundry_from: "%s"' % url + " }"
            line = m.group(1) + rid + rest
            filled.add(rid)
        lines.append(line)
    for rid in fill_map:
        if rid not in filled:
            errors.append("fill target %s not found in constraints.yaml" % rid)
    text = "\n".join(lines)

    block = [MARK_BEGIN,
             "# Generated by generator/extract_foundry_data.py -- DO NOT EDIT BY HAND.",
             "# Values are GF180MCU DRM (Experimental Preview) design-rule DEFAULTS,",
             "# not assembly-house commitments and not a DRC-clean claim.",
             "# drc_clean remains false; capability decision remains NO_GO.",
             "foundry_data_summary:",
             "  source: \"%s\"" % d["meta"]["source"],
             "  source_status: \"%s\"" % d["meta"]["source_status"],
             "  license: \"%s\"" % d["meta"]["license"],
             "  retrieved_on: \"%s\"" % d["meta"]["retrieved_on"],
             "  filled:"]
    for rid, v in sorted(fill_map.items()):
        block.append("    %s: %s" % (rid, v["value_display"]))
    block += ["  deferred:"]
    for x in d["data"]:
        if x["decision"] == "defer":
            reason = x.get("blocked_by", "see note")[:70].strip().rstrip(".")
            block.append("    %s: %s" % (x["id"], reason))
    block += [MARK_END, ""]
    new = "\n".join(block)
    if MARK_BEGIN in text:
        a = text.index(MARK_BEGIN)
        b = text.index(MARK_END, a) + len(MARK_END)
        text = text[:a] + new.rstrip("\n") + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + new
    CONSTRAINTS.write_text(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify only, do not edit")
    args = ap.parse_args()
    d = yaml.safe_load(DATA.read_text())
    errors = []
    validate(d, errors)
    if errors:
        for x in errors:
            print("ERROR " + x, file=sys.stderr)
        return 1

    fill_map = {}
    for x in d["data"]:
        if x["decision"] == "fill":
            fill_map[x["applies_to"]] = {
                "value": x["value"], "value_display": x["value_display"],
                "url": x["source_url"],
            }

    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "foundry_data.json").write_text(json.dumps({
        "generated_by": "generator/extract_foundry_data.py",
        "status": "documented_defaults_no_signoff_claim",
        "meta": d["meta"], "data": d["data"],
    }, indent=2) + "\n")

    md = ["# Foundry / assembly-house data for the deferred pdk_rules", "",
          "Located %s. Source: %s (%s)." %
          (d["meta"]["retrieved_on"], d["meta"]["source"], d["meta"]["source_status"]),
          "", "**These are DRM design-rule DEFAULTS, not assembly-house commitments,",
          "and not proof that any DRC ran.** drc_clean stays false, capability stays NO_GO.",
          "", "| rule | match | decision | value | section |", "|---|---|---|---|---|"]
    for x in d["data"]:
        v = x.get("value_display", "-")
        md.append("| %s | %s | %s | %s | %s |" %
                  (x["id"], x["semantic_match"], x["decision"], v, x.get("drm_section", "-")))
    md += ["", "## Filled (semantic match exact)", ""]
    for x in d["data"]:
        if x["decision"] == "fill":
            md.append("- **%s = %s** (%s). %s" %
                      (x["id"], x["value_display"], x["drm_section"], x["selection"]))
            md.append("  - source: %s" % x["source_url"])
            for c in x["caveats"]:
                md.append("  - caveat: %s" % c)
    md += ["", "## Why the other 6 remain TBD", ""]
    for x in d["data"]:
        if x["decision"] == "defer":
            md.append("- **%s**: %s" % (x["id"], x.get("blocked_by", x.get("note", ""))))
            if x.get("source_url"):
                md.append("  - source: %s (%s)" % (x["source_url"], x.get("drm_section", "")))
            for a in x.get("assembly_sources", []):
                md.append("  - assembly: %s" % a)
            for a in x.get("derived_only", []):
                md.append("  - derived (NOT filled): %s" % a)
    a_search = d["meta"].get("assembly_search")
    if a_search:
        md += ["", "## Assembly / bonding diagram search (%s)" % a_search["searched_on"],
               "", "**Q: %s**" % a_search["question"],
               "", "- found: %s" % a_search["found"],
               "- explicit pad pitch value: %s" % a_search["pad_pitch_value"],
               "- status: %s" % a_search["pad_pitch_status"],
               "- reason: %s" % a_search["reason"], ""]
    md += ["", "## Honesty boundaries", "",
           "- Docs site says work in progress / Experimental Preview.",
           "- DRM 9.2: bond-pad numbers are DRC defaults, VARIABLE, must be confirmed with the assembly house.",
           "- DRM 9.0: pad size and pitch are limited by the assembly house; no center-to-center pitch is given.",
           "- DRM 14.4: TLP-to-HBM miscorrelation is acknowledged; no HBM/MM target level is specified.",
           "- Web sources cannot be re-opened offline, unlike the live-checked local PDK files.", ""]
    (REPORTS / "foundry_data.md").write_text("\n".join(md))

    if not args.check:
        apply_to_constraints(fill_map, d, errors)
        if errors:
            for x in errors:
                print("ERROR " + x, file=sys.stderr)
            return 1
    print("foundry data checks PASS: %d filled (foundry_doc), %d deferred, all sourced" %
          (len(fill_map), len(d["data"]) - len(fill_map)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
