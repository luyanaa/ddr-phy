"""Verify and apply gf180mcuD PDK rule evidence to constraints.yaml.

Unlike the device extractor (which measures transistors), this reads PDK
DESIGN RULE files and checks every claim LIVE against the local PDK:
  - verified sources must exist, the cited line must contain the snippet
  - related/not_in_pdk candidates are checked for existence (no numbers used)
Only rules with verdict=verified AND decision=fill are written into
pdk_rules. The other 8 stay TBD with an explicit reason. Filled values are
rule LIMITS, not proof that any DRC ran: drc_clean stays false everywhere.

Usage: python3 generator/extract_pdk_rules.py [--check]
"""
import argparse
import glob
import json
import os
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
EVIDENCE = ROOT / "specs" / "pads" / "pdk_rule_evidence.yaml"
CONSTRAINTS = ROOT / "specs" / "pads" / "constraints.yaml"
REPORTS = ROOT / "reports"
MARK_BEGIN = "# === BEGIN GENERATED pdk_rule_evidence ==="
MARK_END = "# === END GENERATED pdk_rule_evidence ==="
ROOT_GLOB = "~/.ciel/ciel/gf180mcu/versions/*/gf180mcuD"
ROOT_MUST = "libs.tech/klayout/tech/drc/rule_decks/metal.rb"


def discover():
    hits = sorted(glob.glob(os.path.expanduser(ROOT_GLOB)))
    valid = [h for h in hits if (Path(h) / ROOT_MUST).exists()]
    return Path(valid[-1]) if valid else None


def check_source(root, rel, line_no, snippet, errors, tag):
    """A cited file:line must exist and contain the snippet, live."""
    f = root / rel
    if not f.exists():
        errors.append("%s: source file missing: %s" % (tag, rel))
        return False
    if line_no is None or snippet is None:
        return True
    lines = f.read_text(errors="ignore").splitlines()
    if not (1 <= line_no <= len(lines)):
        errors.append("%s: %s has no line %d" % (tag, rel, line_no))
        return False
    if snippet not in lines[line_no - 1]:
        errors.append("%s: %s:%d does not contain [%s]" % (tag, rel, line_no, snippet))
        return False
    return True


def check_candidate(root, cand, errors, tag):
    """A candidate 'path:line text' must at least point to a real file."""
    m = re.match(r"^(\S+?\.[\w]+):?(\d*)", cand)
    rel = m.group(1) if m else cand.split(":")[0]
    f = root / rel
    if not f.exists():
        errors.append("%s: candidate file missing: %s" % (tag, rel))
        return False
    return True


def apply_to_constraints(fill_map, evidence, errors):
    text = CONSTRAINTS.read_text()
    new_lines = []
    filled = set()
    for line in text.splitlines():
        m = re.match(r"^(\s*-\s*\{id:\s*)([A-Z_]+)(,.*)$", line)
        if m and m.group(2) in fill_map:
            rid, rest = m.group(2), m.group(3)
            val = fill_map[rid]
            src = next(r for r in evidence["rules"] if r["id"] == rid)
            origin = "%s:%d" % (src["source"], src["source_line"])
            rest = re.sub(r"value:\s*null", "value: %s" % val, rest)
            rest = re.sub(r"status:\s*(TBD|verified)", "status: verified", rest)
            rest = re.sub(r",\s*verified_from:\s*\"[^\"]*\"", "", rest)
            rest = rest.rstrip()
            # inject provenance before the closing brace
            if rest.endswith("}"):
                rest = rest[:-1].rstrip() + ', verified_from: "%s"' % origin + " }"
            line = m.group(1) + rid + rest
            filled.add(rid)
        new_lines.append(line)
    for rid in fill_map:
        if rid not in filled:
            errors.append("fill target %s not found in constraints.yaml" % rid)
    text = "\n".join(new_lines)

    block = [MARK_BEGIN,
             "# Generated by generator/extract_pdk_rules.py -- DO NOT EDIT BY HAND.",
             "# Filled values are PDK rule LIMITS with live-checked provenance.",
             "# drc_clean is still false; capability decision is still NO_GO.",
             "pdk_rule_evidence_summary:",
             "  pdk: %s" % evidence["meta"]["pdk"],
             "  pdk_version: %s" % evidence["meta"]["pdk_version"],
             "  verified_on: \"%s\"" % evidence["meta"]["verified_on"],
             "  filled:"]
    for rid, val in sorted(fill_map.items()):
        block.append("    %s: %s" % (rid, val))
    block += ["  deferred:"]
    for r in evidence["rules"]:
        if r["decision"] == "defer":
            block.append("    %s: %s" % (r["id"], r["verdict"]))
    block += [MARK_END, ""]
    new = "\n".join(block)
    if MARK_BEGIN in text:
        a = text.index(MARK_BEGIN)
        b = text.index(MARK_END, a) + len(MARK_END)
        text = text[:a] + new.rstrip("\n") + text[b:]
    else:
        text = text.rstrip("\n") + "\n\n" + new
    CONSTRAINTS.write_text(text)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify only, do not edit")
    args = ap.parse_args()

    evidence = yaml.safe_load(EVIDENCE.read_text())
    root = discover()
    errors = []
    if root is None:
        print("ERROR gf180mcuD PDK with metal.rb not found", file=sys.stderr)
        return 1

    fill_map = {}
    for r in evidence["rules"]:
        tag = r["id"]
        if r["verdict"] == "verified" and r["decision"] == "fill":
            if "value" not in r or "source" not in r or "source_line" not in r:
                errors.append("%s: verdict=verified but missing value/source" % tag)
                continue
            ok = check_source(root, r["source"], r["source_line"],
                              r["source_snippet"], errors, tag)
            if ok:
                fill_map[tag] = r["value"]
        else:
            for c in r.get("candidates", []):
                check_candidate(root, c, errors, tag)
            if r["verdict"] == "verified":
                errors.append("%s: verdict=verified but decision is not fill" % tag)

    if errors:
        for x in errors:
            print("ERROR " + x, file=sys.stderr)
        return 1

    detail = {
        "generated_by": "generator/extract_pdk_rules.py",
        "pdk": evidence["meta"]["pdk"],
        "pdk_version": evidence["meta"]["pdk_version"],
        "pdk_root": str(root),
        "status": "rule_limits_only_no_drc_claim",
        "filled": fill_map,
        "rules": evidence["rules"],
    }
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "pdk_rule_evidence.json").write_text(json.dumps(detail, indent=2) + "\n")

    md = ["# gf180mcuD PDK rule evidence", "",
          "Generated by generator/extract_pdk_rules.py. Every verified value was",
          "checked live against the local PDK file:line on %s." % evidence["meta"]["verified_on"],
          "",
          "**Filled values are DRC rule limits, not proof that a DRC ran.**",
          "drc_clean remains false; capability decision remains NO_GO.", "",
          "| rule | verdict | decision | value | source |", "|---|---|---|---|---|"]
    for r in evidence["rules"]:
        v = r.get("value", "-")
        s = r.get("source", "-")
        if s != "-":
            s = "%s:%s" % (s, r.get("source_line", "?"))
        md.append("| %s | %s | %s | %s | %s |" %
                  (r["id"], r["verdict"], r["decision"], v, s))
    md += ["", "## Why 8 rules remain TBD", ""]
    for r in evidence["rules"]:
        if r["decision"] == "defer":
            md.append("- **%s** (%s): %s" % (r["id"], r["verdict"], r["reason"]))
    md += ["", "## Filled now", ""]
    for rid, val in sorted(fill_map.items()):
        md.append("- %s = %s (verified live)" % (rid, val))
    md += ["", "Not performed: running DRC on a real pad layout, ESD/HBM",
           "qualification, metal EM/IR signoff, latch-up verification.", ""]
    (REPORTS / "pdk_rule_evidence.md").write_text("\n".join(md))

    if not args.check:
        apply_to_constraints(fill_map, evidence, errors)
        if errors:
            for x in errors:
                print("ERROR " + x, file=sys.stderr)
            return 1

    print("pdk rule evidence checks PASS: %d filled, %d deferred, live sources verified" %
          (len(fill_map), len(evidence["rules"]) - len(fill_map)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
