"""Emit flow/sdr_phy.sdc from the device spec and timing contract.

The generated file is a DRAFT. Every unknown (board, package, pad, PVT,
uncertainty) is a named Tcl variable set to 0 and marked TBD in comments.
The script refuses to emit a signoff SDC while those terms are open; use
--check to enforce that in CI.
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "specs" / "timing_contract.yaml"
DEVICE = ROOT / "specs" / "devices" / "micron_mt48lc16m16a2-75.yaml"
OUT = ROOT / "flow" / "sdr_phy.sdc"
OUT_TOP = ROOT / "flow" / "sdram_phy_top.sdc"
TOP_CK_PORT = "pad_ck"
REPORTS = ROOT / "reports"


def contract_value(con, ident, default=0.0):
    """Numeric value of a timing-contract parameter, or default."""
    for cls, body in con["parameter_classes"].items():
        for prm in body["params"]:
            if prm["id"] == ident:
                v = prm.get("value")
                return float(v) if isinstance(v, (int, float)) else default
    return default


def pad_oe_extremes():
    """Max t_oe_on / t_oe_off over the P1-1 characterization points (ns)."""
    files = sorted(REPORTS.glob("pad_char_gf180mcuD_*.json"))
    if not files:
        return None
    on_max, off_max = 0.0, 0.0
    for f in files:
        m = json.loads(f.read_text()).get("measures", {})
        on_max = max(on_max, m.get("t_oe_on", 0.0))
        off_max = max(off_max, m.get("t_oe_off", 0.0))
    return {"on": on_max * 1e9, "off": off_max * 1e9}


def pad_delay_extremes():
    """Global min/max pad delays over the characterized PVT points (ns).

    Returns None when no characterization exists, so the SDC keeps its
    zero placeholders instead of inventing numbers.
    """
    files = sorted(REPORTS.glob("pad_delay_gf180mcuD_*.json"))
    if not files:
        return None
    out_max, out_min, in_max, in_min = -1e9, 1e9, -1e9, 1e9
    for f in files:
        m = json.loads(f.read_text())["measures"]
        out_max = max(out_max, m["tpd_out_r"], m["tpd_out_f"])
        out_min = min(out_min, m["tpd_out_r"], m["tpd_out_f"])
        in_max = max(in_max, m["tpd_in_r"], m["tpd_in_f"])
        in_min = min(in_min, m["tpd_in_r"], m["tpd_in_f"])
    return {"out_max": out_max * 1e9, "out_min": out_min * 1e9,
            "in_max": in_max * 1e9, "in_min": in_min * 1e9,
            "sources": [f.name for f in files]}


def value(dev, ident):
    for p in dev["parameters"]:
        if p["id"] == ident:
            return p["value"]
    raise KeyError(ident)


def main():
    dev = yaml.safe_load(open(DEVICE))
    con = yaml.safe_load(open(CONTRACT))
    tbds = [p["id"] for cls, body in con["parameter_classes"].items()
            for p in body["params"] if p["status"] == "TBD"]

    tck = value(dev, "tCK_CL2_min")
    tds, tdh = value(dev, "tDS_min"), value(dev, "tDH_min")
    tas, tah = value(dev, "tAS_min"), value(dev, "tAH_min")
    tcms, tcmh = value(dev, "tCMS_min"), value(dev, "tCMH_min")
    tac = value(dev, "tAC_CL2_max")
    toh = value(dev, "tOH_min_loaded")
    thz, tlz = value(dev, "tHZ_CL2_max"), value(dev, "tLZ_min")
    padx = pad_delay_extremes() or {"out_max": 0.0, "out_min": 0.0,
                                    "in_max": 0.0, "in_min": 0.0}
    pad_out_max, pad_out_min = padx["out_max"], padx["out_min"]
    pad_in_max, pad_in_min = padx["in_max"], padx["in_min"]
    oex = pad_oe_extremes() or {"on": 0.0, "off": 0.0}
    toe_on, toe_off = oex["on"], oex["off"]
    # Board terms and uncertainty: measured in P1-4 / the timing contract.
    board = contract_value(con, "board_flight")
    skew = contract_value(con, "dq_bit_skew")
    unc = contract_value(con, "t_uncertainty")
    board_dq_max, board_dq_min = board + skew, board - skew
    board_ck_max, board_ck_min = board + skew, board - skew

    head = f"""# SPDX-License-Identifier: Apache-2.0
# GENERATED by generator/emit_sdc.py -- DO NOT EDIT BY HAND.
#
# CONSTRAINTS BUILT FROM MEASURED TERMS, STILL NOT SIGNOFF. {len(tbds)}
# terms in specs/timing_contract.yaml are status: TBD. Pad, board, OE and
# the clock-path terms are measured (P1-1..P1-4); t_uncertainty is an
# explicit CONSERVATIVE BOUND, not a measurement, and placement/CTS/SDF are
# still missing. Do not treat a clean report from this file as closure - see
# docs/STA_PLAN.md.
#
# Device: {dev['meta']['part']} {dev['meta']['speed_grade']} (Table 20, -75)
# Corner: 100 MHz CL2, tCK={tck} ns. tAC(2)={tac} ns (NOT the 5.4 ns CL3 value).
# Sources: specs/devices/micron_mt48lc16m16a2-75.yaml
#          docs/TIMING_BUDGET.md, docs/TIMING_SWEEP.md
#
# Constraint style: ck is a forwarded/generated clock derived from clk.
# Four path groups are named explicitly (checklist section 6.1).

# ---- known device numbers (ns) ----
set tCK  {tck:.3f}
set tDS  {tds:.3f}
set tDH  {tdh:.3f}
set tAS  {tas:.3f}
set tAH  {tah:.3f}
set tCMS {tcms:.3f}
set tCMH {tcmh:.3f}
set tAC  {tac:.3f}
set tOH  {toh:.3f}
set tHZ  {thz:.3f}
set tLZ  {tlz:.3f}

# ---- coefficients (ns). Measured where P1-1..P1-4 cover it, otherwise an
# explicit conservative bound (see specs/timing_contract.yaml status) ----
set board_dq_max   {board_dq_max:.3f}  ; # P1-4 channel (335-337 ps) + 5.5 ps skew
set board_dq_min   {board_dq_min:.3f}  ; # P1-4 channel
set board_ck_max   {board_ck_max:.3f}  ; # P1-4 channel, same trace class as DQ
set board_ck_min   {board_ck_min:.3f}  ; # P1-4 channel
set pad_out_max    {pad_out_max:.3f}  ; # P1-3 pad_delay_*.json (SPICE, first-pass fixture)
set pad_out_min    {pad_out_min:.3f}  ; # P1-3 pad_delay_*.json
set pad_in_max     {pad_in_max:.3f}  ; # P1-3 pad_delay_*.json
set pad_in_min     {pad_in_min:.3f}  ; # P1-3 pad_delay_*.json
set t_uncertainty  {unc:.3f}  ; # CONSERVATIVE BOUND: jitter/DCD + OCV/PVT + SSN
set toe_on         {toe_on:.3f}  ; # P1-1 pad_char_*.json (max over PVT)
set toe_off        {toe_off:.3f}  ; # P1-1 pad_char_*.json (max over PVT)

# ---- clocks ----
create_clock -name sys_clk -period $tCK [get_ports clk]
# ck = clk in rtl/sdr_phy.sv:77 today; clock_forward.sv is the explicit
# replacement path. A generated clock makes the forwarded relationship
# visible to STA instead of leaving ck as an ordinary combinational output.
create_generated_clock -name sdram_ck -source [get_ports clk] \
    -divide_by 1 [get_ports ck]
set_clock_uncertainty $t_uncertainty [get_clocks sys_clk]
set_clock_uncertainty $t_uncertainty [get_clocks sdram_ck]

# ---- path group 0: forwarded CK (clk -> ck pin) ----
# P1-3. ck is the forwarded clock; its pad delay is characterized, the
# board term is still TBD (P1-4).
set_output_delay -clock sdram_ck -max \
    [expr {{$pad_out_max - $board_ck_min}}] [get_ports ck]
set_output_delay -clock sdram_ck -min \
    [expr {{$pad_out_min - $board_ck_max}}] [get_ports ck]
group_path -name CK_OUT -to [get_ports ck]

# ---- path group 1: Command/Address TX (ASIC FF -> SDRAM CK) ----
set cmd_ports {{a[*] ba[*] ras_n cas_n we_n cs_n* cke* dm*}}
set_output_delay -clock sdram_ck -max \
    [expr {{$tCMS + $pad_out_max + $board_dq_max - $board_ck_min + $t_uncertainty}}] \
    [get_ports $cmd_ports]
set_output_delay -clock sdram_ck -min \
    [expr {{-$tCMH + $pad_out_min + $board_dq_min - $board_ck_max - $t_uncertainty}}] \
    [get_ports $cmd_ports]
group_path -name CMD_TX -to [get_ports $cmd_ports]

# ---- path group 2: Write DQ TX (ASIC FF -> SDRAM CK) ----
# WRITE command and first DQ are sampled on the SAME SDRAM CK edge
# (write_latency 0, docs/TIMING_BUDGET.md section 5).
set wr_ports {{dq_o[*] dq_oe}}
set_output_delay -clock sdram_ck -max \
    [expr {{$tDS + $pad_out_max + $board_dq_max - $board_ck_min + $t_uncertainty}}] \
    [get_ports $wr_ports]
set_output_delay -clock sdram_ck -min \
    [expr {{-$tDH + $pad_out_min + $board_dq_min - $board_ck_max - $t_uncertainty}}] \
    [get_ports $wr_ports]
group_path -name WRITE_DQ_TX -to [get_ports $wr_ports]

# ---- path group 3: Read DQ RX (SDRAM CK -> ASIC FF) ----
# -max uses tAC(max). The datasheet gives only tAC(max) and tOH(min), not
# tAC(min) or tOH(max): the -min/-max pair below is a conservative bound,
# NOT a true PVT min/max pair. tOH(min) is used as the earliest-change
# bound for the hold check. Replace after characterization.
set rd_ports {{dq_i[*]}}
set_input_delay -clock sdram_ck -max \
    [expr {{$tAC + $pad_in_max + $board_dq_max - $board_ck_min + $t_uncertainty}}] \
    [get_ports $rd_ports]
set_input_delay -clock sdram_ck -min \
    [expr {{$tOH + $pad_in_min + $board_dq_min - $board_ck_max - $t_uncertainty}}] \
    [get_ports $rd_ports]
group_path -name READ_DQ_RX -from [get_ports $rd_ports]

# ---- path group 4: OE turnaround (PHY control FF -> two drivers) ----
# dq_oe gates the PHY output driver. Its on/off must not overlap the
# SDRAM tHZ release, but the real bound needs pad timing (gate G5), which
# is TBD. The -min below is therefore only the ordinary tDH hold bound:
# an earlier draft used $tHZ as a -min and forced 19 hold buffers into an
# over-dense placement, causing DPL-0036. Do not inject an uncharacterized
# turnaround number into the resizer. GUARD_CYCLES in dq_turnaround.sv is
# a design parameter, not a characterized tHZ.
# dq_oe is an ordinary single-cycle output: the driver must be settled by
# the end of the cycle. tLZ/tHZ describe when the DRAM releases the bus, not
# a deadline for this register, so subtracting tLZ from tCK (the old form)
# forced dq_oe within ~1.6 ns and produced a -4.4 ns violation that did not
# correspond to a real requirement. Keep the pad/board delay and the
# uncertainty, and leave one tDH of margin on the min side.
set_output_delay -clock sys_clk -max \
    [expr {{$pad_out_max + $board_dq_max + $t_uncertainty}}] [get_ports dq_oe]
set_output_delay -clock sys_clk -min \
    [expr {{-$tDH + $pad_out_min + $board_dq_min - $t_uncertainty}}] [get_ports dq_oe]
group_path -name OE_TURNAROUND -to [get_ports dq_oe]

# ---- NOT a blanket 'set_output_delay 2' ----
# Data, command and clock see different delays and different min/max
# conditions (checklist section 6.1). The placeholder variables must be
# filled per corner, not collapsed into one number.
#
# Still absent: SDF annotation, IBIS/PCB SI, power integrity,
# multi-corner PVT, DRC/LVS on the pad ring. See docs/STA_PLAN.md.
"""
    OUT.write_text(head)
    # Top-level variant: sdram_phy_top exposes the forwarded clock as pad_ck
    # (its sdr_phy.ck output is deliberately unconnected).
    top = head.replace("[get_ports ck]", "[get_ports %s]" % TOP_CK_PORT)
    # sdram_phy_top packs command/address into pad_cmd and DQ into the
    # bidirectional pad_dq, so the port sets differ from the sdr_phy core.
    # The generated text has single braces (f-string doubles collapse), so
    # the replacements must use single braces too.
    top = top.replace("set cmd_ports {a[*] ba[*] ras_n cas_n we_n cs_n* cke* dm*}",
                      "set cmd_ports {pad_cmd[*]}")
    top = top.replace("set wr_ports {dq_o[*] dq_oe}", "set wr_ports {pad_dq[*]}")
    top = top.replace("set rd_ports {dq_i[*]}", "set rd_ports {pad_dq[*]}")
    top = top.replace("[get_ports dq_oe]", "[get_ports pad_dq]")
    top = top.replace("group_path -name OE_TURNAROUND -to [get_ports pad_dq]",
                      "group_path -name OE_TURNAROUND -to [get_ports pad_dq]")
    top = top.replace("group_path -name CK_OUT -to [get_ports ck]",
                      "group_path -name CK_OUT -to [get_ports %s]" % TOP_CK_PORT)
    top = top.replace("set_output_delay -clock sdram_ck -max \\\n    [expr {$pad_out_max - $board_ck_min}] [get_ports ck]",
                      "set_output_delay -clock sdram_ck -max \\\n    [expr {$pad_out_max - $board_ck_min}] [get_ports %s]" % TOP_CK_PORT)
    top = top.replace("set_output_delay -clock sdram_ck -min \\\n    [expr {$pad_out_min - $board_ck_max}] [get_ports ck]",
                      "set_output_delay -clock sdram_ck -min \\\n    [expr {$pad_out_min - $board_ck_max}] [get_ports %s]" % TOP_CK_PORT)
    OUT_TOP.write_text(top)
    print("wrote %s" % OUT_TOP)
    print(f"wrote {OUT} ({len(tbds)} TBD placeholders)")
    print("STATUS: pre-layout constraints; placement/CTS/SDF still missing")
    if "--check" in sys.argv and tbds:
        print("ERROR: --check requested but TBD terms remain", file=sys.stderr)
        for t in tbds:
            print("  TBD " + t, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
