#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0
"""Emit flow/sdr_phy.sdc from the device spec and timing contract.

The generated file is a DRAFT. Every unknown (board, package, pad, PVT,
uncertainty) is a named Tcl variable set to 0 and marked TBD in comments.
The script refuses to emit a signoff SDC while those terms are open; use
--check to enforce that in CI.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "specs" / "timing_contract.yaml"
DEVICE = ROOT / "specs" / "devices" / "micron_mt48lc16m16a2-75.yaml"
OUT = ROOT / "flow" / "sdr_phy.sdc"


def value(dev, ident):
    for p in dev["parameters"]:
        if p["id"] == ident:
            return p["value"]
    raise KeyError(ident)


def main():
    dev = yaml.safe_load(open(DEVICE))
    con = yaml.safe_load(open(CONTRACT))
    tbds = [p["id"] for cls, body in con["parameter_classes"].items()
            for p in body["params"] if p["status"] == "TBD"]

    tck = value(dev, "tCK_CL2_min")
    tds, tdh = value(dev, "tDS_min"), value(dev, "tDH_min")
    tas, tah = value(dev, "tAS_min"), value(dev, "tAH_min")
    tcms, tcmh = value(dev, "tCMS_min"), value(dev, "tCMH_min")
    tac = value(dev, "tAC_CL2_max")
    toh = value(dev, "tOH_min_loaded")
    thz, tlz = value(dev, "tHZ_CL2_max"), value(dev, "tLZ_min")

    head = f"""# SPDX-License-Identifier: Apache-2.0
# GENERATED by generator/emit_sdc.py -- DO NOT EDIT BY HAND.
#
# DRAFT CONSTRAINTS, NOT SIGNOFF. {len(tbds)} terms in
# specs/timing_contract.yaml are still status: TBD. Every one of them is
# represented below by a Tcl variable set to 0.0 with a TBD comment.
# With those placeholders at zero the timing looks better than reality.
# Replace them with characterized values from P0-3/pad, package and board
# before any closure claim.
#
# Device: {dev['meta']['part']} {dev['meta']['speed_grade']} (Table 20, -75)
# Corner: 100 MHz CL2, tCK={tck} ns. tAC(2)={tac} ns (NOT the 5.4 ns CL3 value).
# Sources: specs/devices/micron_mt48lc16m16a2-75.yaml
#          docs/TIMING_BUDGET.md, docs/TIMING_SWEEP.md
#
# Constraint style: ck is a forwarded/generated clock derived from clk.
# Four path groups are named explicitly (checklist section 6.1).

# ---- known device numbers (ns) ----
set tCK  {tck:.3f}
set tDS  {tds:.3f}
set tDH  {tdh:.3f}
set tAS  {tas:.3f}
set tAH  {tah:.3f}
set tCMS {tcms:.3f}
set tCMH {tcmh:.3f}
set tAC  {tac:.3f}
set tOH  {toh:.3f}
set tHZ  {thz:.3f}
set tLZ  {tlz:.3f}

# ---- TBD placeholders (ns). NOT characterized: pad, package, PCB, PVT ----
set board_dq_max   0.000  ; # TBD tDQ_return/tDQ_tx max
set board_dq_min   0.000  ; # TBD tDQ_return/tDQ_tx min
set board_ck_max   0.000  ; # TBD tCLK,fwd max
set board_ck_min   0.000  ; # TBD tCLK,fwd min
set pad_out_max    0.000  ; # TBD output pad delay max
set pad_out_min    0.000  ; # TBD output pad delay min
set pad_in_max     0.000  ; # TBD input pad delay max
set pad_in_min     0.000  ; # TBD input pad delay min
set t_uncertainty  0.000  ; # TBD jitter + DCD + OCV + skew + SSN
set toe_on         0.000  ; # TBD tOE_on
set toe_off        0.000  ; # TBD tOE_off

# ---- clocks ----
create_clock -name sys_clk -period $tCK [get_ports clk]
# ck = clk in rtl/sdr_phy.sv:77 today; clock_forward.sv is the explicit
# replacement path. A generated clock makes the forwarded relationship
# visible to STA instead of leaving ck as an ordinary combinational output.
create_generated_clock -name sdram_ck -source [get_ports clk] \
    -divide_by 1 [get_ports ck]
set_clock_uncertainty $t_uncertainty [get_clocks sys_clk]
set_clock_uncertainty $t_uncertainty [get_clocks sdram_ck]

# ---- path group 1: Command/Address TX (ASIC FF -> SDRAM CK) ----
set cmd_ports {{a[*] ba[*] ras_n cas_n we_n cs_n* cke* dm*}}
set_output_delay -clock sdram_ck -max \
    [expr {{$tCMS + $pad_out_max + $board_dq_max - $board_ck_min + $t_uncertainty}}] \
    [get_ports $cmd_ports]
set_output_delay -clock sdram_ck -min \
    [expr {{-$tCMH + $pad_out_min + $board_dq_min - $board_ck_max - $t_uncertainty}}] \
    [get_ports $cmd_ports]
group_path -name CMD_TX -to [get_ports $cmd_ports]

# ---- path group 2: Write DQ TX (ASIC FF -> SDRAM CK) ----
# WRITE command and first DQ are sampled on the SAME SDRAM CK edge
# (write_latency 0, docs/TIMING_BUDGET.md section 5).
set wr_ports {{dq_o[*] dq_oe}}
set_output_delay -clock sdram_ck -max \
    [expr {{$tDS + $pad_out_max + $board_dq_max - $board_ck_min + $t_uncertainty}}] \
    [get_ports $wr_ports]
set_output_delay -clock sdram_ck -min \
    [expr {{-$tDH + $pad_out_min + $board_dq_min - $board_ck_max - $t_uncertainty}}] \
    [get_ports $wr_ports]
group_path -name WRITE_DQ_TX -to [get_ports $wr_ports]

# ---- path group 3: Read DQ RX (SDRAM CK -> ASIC FF) ----
# -max uses tAC(max). The datasheet gives only tAC(max) and tOH(min), not
# tAC(min) or tOH(max): the -min/-max pair below is a conservative bound,
# NOT a true PVT min/max pair. tOH(min) is used as the earliest-change
# bound for the hold check. Replace after characterization.
set rd_ports {{dq_i[*]}}
set_input_delay -clock sdram_ck -max \
    [expr {{$tAC + $pad_in_max + $board_dq_max - $board_ck_min + $t_uncertainty}}] \
    [get_ports $rd_ports]
set_input_delay -clock sdram_ck -min \
    [expr {{$tOH + $pad_in_min + $board_dq_min - $board_ck_max - $t_uncertainty}}] \
    [get_ports $rd_ports]
group_path -name READ_DQ_RX -from [get_ports $rd_ports]

# ---- path group 4: OE turnaround (PHY control FF -> two drivers) ----
# dq_oe gates the PHY output driver. Its on/off must not overlap the
# SDRAM tHZ release, but the real bound needs pad timing (gate G5), which
# is TBD. The -min below is therefore only the ordinary tDH hold bound:
# an earlier draft used $tHZ as a -min and forced 19 hold buffers into an
# over-dense placement, causing DPL-0036. Do not inject an uncharacterized
# turnaround number into the resizer. GUARD_CYCLES in dq_turnaround.sv is
# a design parameter, not a characterized tHZ.
set_output_delay -clock sys_clk -max \
    [expr {{$tCK - $tLZ - $toe_on - $t_uncertainty}}] [get_ports dq_oe]
set_output_delay -clock sys_clk -min \
    [expr {{-$tDH - $t_uncertainty}}] [get_ports dq_oe]
group_path -name OE_TURNAROUND -to [get_ports dq_oe]

# ---- NOT a blanket 'set_output_delay 2' ----
# Data, command and clock see different delays and different min/max
# conditions (checklist section 6.1). The placeholder variables must be
# filled per corner, not collapsed into one number.
#
# Still absent: SDF annotation, PEX/SPICE, IBIS/PCB SI, power integrity,
# multi-corner PVT, DRC/LVS on the pad ring. See docs/STA_PLAN.md.
"""
    OUT.write_text(head)
    print(f"wrote {OUT} ({len(tbds)} TBD placeholders)")
    print("DRAFT: not signoff-ready")
    if "--check" in sys.argv and tbds:
        print("ERROR: --check requested but TBD terms remain", file=sys.stderr)
        for t in tbds:
            print("  TBD " + t, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
